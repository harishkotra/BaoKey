#!/usr/bin/env python3
"""Regenerate firmware/esp32/src/audio_clips.h from macOS `say`.

The host is allowed to talk, so the demo lets it. In the honest build it speaks
the vault's answer; in the hostile build it says "approved" no matter what came
back. Speech is output, never authority -- nothing the vault does depends on it.

Usage: python3 tools/make_audio.py
"""
import os
import struct
import subprocess
import sys
import tempfile
import wave

CLIPS = [
    ("SPK_OK", "Approved. Signed by the vault."),
    ("SPK_NO", "Refused. That address is not on the allowlist."),
    ("SPK_LIE", "Approved. Payment sent."),
]
RATE = 24000
VOICE = os.environ.get("VOICE", "Samantha")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "..", "firmware", "esp32", "src", "audio_clips.h")


def render(text, wav_path):
    aiff = wav_path.replace(".wav", ".aiff")
    subprocess.run(["say", "-v", VOICE, "-o", aiff, text], check=True)
    subprocess.run(["afconvert", "-f", "WAVE", "-d", f"LEI16@{RATE}", "-c", "1",
                    aiff, wav_path], check=True)


def main():
    lines = [
        "// Generated by tools/make_audio.py from macOS `say` -> 24 kHz mono 16-bit.",
        "// The host can speak. Speech is output, not authority.",
        "#pragma once",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
    ]
    with tempfile.TemporaryDirectory() as tmp:
        for name, text in CLIPS:
            wav_path = os.path.join(tmp, name + ".wav")
            render(text, wav_path)
            w = wave.open(wav_path)
            if (w.getframerate(), w.getnchannels(), w.getsampwidth()) != (RATE, 1, 2):
                sys.exit(f"unexpected wav format for {name}")
            data = w.readframes(w.getnframes())
            samples = struct.unpack("<%dh" % (len(data) // 2), data)
            lines.append(f'// "{text}"')
            lines.append(f"static const int16_t {name}[] = {{")
            for i in range(0, len(samples), 16):
                lines.append("  " + ",".join(str(s) for s in samples[i:i + 16]) + ",")
            lines.append("};")
            lines.append(f"static const size_t {name}_N = sizeof({name}) / sizeof({name}[0]);")
            lines.append("")
            print(f"{name}: {len(samples)} samples ({len(samples) / RATE:.2f}s)", flush=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
